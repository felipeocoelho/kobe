-- Migration 015 — os documentos alcançáveis pela busca (2026-11-03)
--
-- Highlander v3, F7.2. Redesenho aprovado pelo operador em 02/11/2026 (#4251),
-- com os ajustes de 03/11. Até aqui o `kobe-remember` alcançava a CONVERSA
-- (`messages`) e a TABELA DE FATOS (`lucien_claims`). Os documentos — planos das
-- salas, anotações do agente, base do tópico, material de trabalho do operador —
-- só eram achados se alguém lembrasse que existiam e fizesse `grep`.
--
-- ┌────────────────────────────────────────────────────────────────────────┐
-- │ ESTA MIGRATION NÃO É DESTRUTIVA.                                       │
-- │   Só CRIA três tabelas novas e os índices delas. Não altera nenhuma    │
-- │   tabela existente. Reaplicá-la não faz nada de novo.                  │
-- └────────────────────────────────────────────────────────────────────────┘
--
-- DOCUMENTO NÃO É VERDADE — É O QUE UM DOCUMENTO DIZ
-- --------------------------------------------------
-- Um plano que a sala escreveu e o operador recusou não é "verdade fraca": é
-- proposta recusada. Por isso documento NÃO entra em `lucien_claims`, e toda
-- leitura sai com a NATUREZA na frente — e, para artefato de sala, com o
-- DESFECHO, que nasce `desconhecido` e só muda por fonte registrada.
--
-- AS QUATRO NATUREZAS
-- -------------------
--   artefato_sala      plano/brief/missão: "a sala produziu isto" (+ desfecho)
--   anotacao_agente    a base `knowledge/` do agente: registro de segunda mão
--   base_topico        `topics/<slug>/knowledge/`: o que o operador pôs para valer
--   material_operador  todo o resto de `topics/<slug>/`: "o documento diz…"
--
-- O ARQUIVO NUNCA É TOCADO
-- ------------------------
-- O indexador só LÊ. O texto fica preservado em `content` — é o que mantém a
-- citação viva se um dia o arquivo sair do disco (status `ausente_do_disco`;
-- a linha nunca é apagada).
--
-- CAMINHO RELATIVO, NUNCA ABSOLUTO
-- --------------------------------
-- `root` é o NOME da raiz (`casa`, `salas`…); `rel_path` é relativo a ela. O
-- caminho absoluto é resolvido em tempo de execução pela configuração da
-- instalação — o banco não carrega a topologia de ninguém.
--
-- O VETOR
-- -------
-- O mesmo `text-embedding-3-small` (1536d) da conversa, pelo mesmo
-- `bot/search/embedder.py`. Vetor de modelo diferente no mesmo índice erra
-- calado; um embedder só é o que impede isso.
--
-- ROLLBACK
-- --------
-- `DOC_INDEX_ENABLED=false`: as tabelas ficam inertes e o `kobe-remember` volta
-- a duas camadas. Sair de vez seria `DROP` das três tabelas (sem dependentes),
-- que não está previsto.

CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS vector;

-- ============================================================================
-- doc_sources — um documento
-- ============================================================================

CREATE TABLE IF NOT EXISTS doc_sources (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  root          TEXT NOT NULL,
  rel_path      TEXT NOT NULL,
  nature        TEXT NOT NULL
    CHECK (nature IN ('artefato_sala', 'anotacao_agente', 'base_topico', 'material_operador')),
  topic_slug    TEXT,
  title         TEXT NOT NULL,
  ext           TEXT NOT NULL,
  size_bytes    BIGINT NOT NULL,
  file_mtime    TIMESTAMPTZ,
  sha256        TEXT,
  indexable     BOOLEAN NOT NULL,
  content       TEXT,
  status        TEXT NOT NULL DEFAULT 'presente'
    CHECK (status IN ('presente', 'ausente_do_disco')),
  first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (root, rel_path),
  -- Binário é só listado: não tem texto, e por isso não tem trecho nem vetor.
  CHECK (indexable OR content IS NULL)
);

CREATE INDEX IF NOT EXISTS idx_doc_sources_topic ON doc_sources(topic_slug);
-- A perna literal sobre o NOME: é por ela que um PDF (sem texto) é achável.
CREATE INDEX IF NOT EXISTS idx_doc_sources_path_trgm
  ON doc_sources USING gin(rel_path gin_trgm_ops);

-- ============================================================================
-- doc_chunks — o pedaço buscável
-- ============================================================================

CREATE TABLE IF NOT EXISTS doc_chunks (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_id      BIGINT NOT NULL REFERENCES doc_sources(id) ON DELETE CASCADE,
  idx         INT NOT NULL,
  anchor      TEXT,
  body        TEXT NOT NULL,
  search_tsv  tsvector GENERATED ALWAYS AS (to_tsvector('portuguese', body)) STORED,
  embedding   VECTOR(1536),
  model       TEXT,
  embedded_at TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (doc_id, idx)
);

CREATE INDEX IF NOT EXISTS idx_doc_chunks_pendentes
  ON doc_chunks(id) WHERE embedding IS NULL;
CREATE INDEX IF NOT EXISTS idx_doc_chunks_doc ON doc_chunks(doc_id);
CREATE INDEX IF NOT EXISTS idx_doc_chunks_tsv ON doc_chunks USING gin(search_tsv);
CREATE INDEX IF NOT EXISTS idx_doc_chunks_body_trgm
  ON doc_chunks USING gin(body gin_trgm_ops);

-- ============================================================================
-- doc_producoes — o catálogo do que as salas produziram (gaveta 1)
-- ============================================================================
-- O campo que resolve tudo é o DESFECHO. Ele nasce `desconhecido`, e só muda por
-- uma fonte nomeada em `outcome_source`:
--   estado_coder  o Coder gravou `plan_approved` quando o operador aprovou
--   fim_da_sala   a sala terminou sem aprovação registrada → sem_resposta
--   operador      comando com o `#número` da fala dele (`origin_seq`) — é a
--                 ÚNICA porta de `recusado` e `superado`.

CREATE TABLE IF NOT EXISTS doc_producoes (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_id         BIGINT NOT NULL UNIQUE REFERENCES doc_sources(id) ON DELETE CASCADE,
  sala_id        TEXT NOT NULL,
  sala_kind      TEXT NOT NULL CHECK (sala_kind IN ('coder', 'missao')),
  produced_at    TIMESTAMPTZ,
  outcome        TEXT NOT NULL DEFAULT 'desconhecido'
    CHECK (outcome IN ('aprovado', 'recusado', 'sem_resposta', 'superado', 'desconhecido')),
  outcome_source TEXT
    CHECK (outcome_source IS NULL OR outcome_source IN ('estado_coder', 'fim_da_sala', 'operador')),
  outcome_at     TIMESTAMPTZ,
  origin_seq     BIGINT,
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Desfecho conhecido exige fonte; recusado/superado exigem a fala dele.
  CHECK (outcome = 'desconhecido' OR outcome_source IS NOT NULL),
  CHECK (outcome NOT IN ('recusado', 'superado')
         OR (outcome_source = 'operador' AND origin_seq IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS idx_doc_producoes_sala ON doc_producoes(sala_id);
