-- Migration 016 — o documento ligado ao assunto (2026-11-03)
--
-- Highlander v3, F7.2. Decisão do operador em 03/11/2026 (17:09, opção 1): a
-- ligação documento↔assunto é feita por MODELO — o curador (LUCIEN), em segundo
-- plano, com o modelo padrão do Kobe pela assinatura.
--
-- ┌────────────────────────────────────────────────────────────────────────┐
-- │ ESTA MIGRATION NÃO É DESTRUTIVA.                                       │
-- │   CRIA uma tabela (`doc_subjects`), ACRESCENTA três colunas nulas em   │
-- │   `doc_sources` e três contadores com default zero em `lucien_runs`, e │
-- │   ALARGA uma restrição (o modo da rodada passa a aceitar um valor a    │
-- │   mais — mesmo padrão da 012 e da 013). Não apaga linha, coluna nem    │
-- │   tabela, e não altera nenhuma linha existente. Reaplicá-la não faz    │
-- │   nada de novo.                                                        │
-- └────────────────────────────────────────────────────────────────────────┘
--
-- POR QUE POR MODELO, E NÃO SÓ PELA BUSCA — MEDIDO
-- ------------------------------------------------
-- No laboratório (03/11), 14 assuntos reais × 597 documentos, orçamento de 5
-- documentos mostrados no "retoma o assunto X": a busca sozinha achou 0,66–0,71
-- dos documentos certos; a ligação por modelo, 0,89. A busca cai exatamente
-- quando a frase usa outras palavras ("aquela vez que a produção ficou rodando
-- versão velha" achou 0 de 5 documentos do incidente do rsync).
--
-- A LIGAÇÃO É JULGAMENTO DE UM MODELO — E A TABELA DIZ DE QUEM
-- ------------------------------------------------------------
-- `origin` separa as três fontes possíveis de uma ligação:
--   ligador   o curador leu o documento e julgou que ele é sobre o assunto;
--   operador  o operador disse (porta futura; nenhuma escrita hoje);
--   autoria   o documento foi ESCRITO para o assunto — é o caso do resumo por
--             assunto que a F7.3 vai gerar. Não é julgamento: é procedência.
-- O ligador só cria e só aposenta linhas `ligador`. As outras duas ele nunca toca.
--
-- APOSENTAR, NÃO APAGAR
-- ---------------------
-- Quando um documento muda e o curador relê, as ligações antigas que ele não
-- repete são APOSENTADAS (`retired_at`, `retired_run_id`), não apagadas. Desfazer
-- uma rodada é: tirar as linhas que ela criou, desaposentar as que ela aposentou
-- e marcar como não-lidos os documentos que ela leu. Tudo por `run_id`.
--
-- FUSÃO É APONTAR
-- ---------------
-- Mesma disciplina da 013: a ligação nunca é reescrita quando dois assuntos se
-- fundem. A leitura segue `merged_into` (a família do assunto).
--
-- ROLLBACK
-- --------
-- `DOC_SUBJECTS_ENABLED=false` faz o curador parar de ligar e o dossiê parar de
-- ler a ligação (volta a mostrar só a busca). Para desfazer uma rodada:
--     bot/bin/kobe-docs desfazer-ligacao <run_id>
-- A tabela e as colunas ficam inertes. Sair de vez seria uma migration de
-- remoção, que não está prevista.

-- ============================================================================
-- doc_subjects — documento ↔ assunto
-- ============================================================================

CREATE TABLE IF NOT EXISTS doc_subjects (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_id         BIGINT NOT NULL REFERENCES doc_sources(id) ON DELETE CASCADE,
  subject_id     UUID NOT NULL REFERENCES lucien_subjects(id) ON DELETE CASCADE,
  origin         TEXT NOT NULL DEFAULT 'ligador',
  -- A versão do documento que foi lida para ligar (o sha256 de `doc_sources`
  -- naquele momento). Se o arquivo mudou depois, a ligação é de uma versão velha
  -- até a próxima leitura — e isto deixa isso visível.
  doc_sha256     TEXT,
  run_id         UUID REFERENCES lucien_runs(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  retired_at     TIMESTAMPTZ,
  retired_run_id UUID REFERENCES lucien_runs(id) ON DELETE SET NULL,

  CONSTRAINT doc_subjects_origin_check
    CHECK (origin IN ('ligador', 'operador', 'autoria')),
  -- Aposentada e "por qual rodada" andam juntas só para o ligador; o operador
  -- (porta futura) pode aposentar sem rodada.
  CONSTRAINT doc_subjects_aposentada_check
    CHECK (retired_run_id IS NULL OR retired_at IS NOT NULL)
);

-- Um documento liga a um assunto UMA vez entre as vigentes, venha de onde vier.
CREATE UNIQUE INDEX IF NOT EXISTS uq_doc_subjects_vigente
  ON doc_subjects(doc_id, subject_id) WHERE retired_at IS NULL;
-- A leitura quente do dossiê: "que documentos este assunto tem?".
CREATE INDEX IF NOT EXISTS idx_doc_subjects_assunto
  ON doc_subjects(subject_id) WHERE retired_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_doc_subjects_run
  ON doc_subjects(run_id);
CREATE INDEX IF NOT EXISTS idx_doc_subjects_retired_run
  ON doc_subjects(retired_run_id) WHERE retired_run_id IS NOT NULL;

-- ============================================================================
-- doc_sources — que versão do documento o curador já leu
-- ============================================================================
-- `linked_sha256` diferente de `sha256` = o documento é novo ou mudou desde a
-- última leitura do ligador: está na fila. Um documento lido que não pertence a
-- assunto nenhum (a maioria) também fica com `linked_sha256` — é isso que impede
-- de pagá-lo de novo a cada rodada.

ALTER TABLE doc_sources ADD COLUMN IF NOT EXISTS linked_sha256 TEXT;
ALTER TABLE doc_sources ADD COLUMN IF NOT EXISTS linked_at     TIMESTAMPTZ;
ALTER TABLE doc_sources ADD COLUMN IF NOT EXISTS link_run_id   UUID
  REFERENCES lucien_runs(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_doc_sources_link_run
  ON doc_sources(link_run_id) WHERE link_run_id IS NOT NULL;

-- ============================================================================
-- lucien_runs — o modo `documentos` e os três contadores
-- ============================================================================
-- Os contadores existem pelo mesmo motivo do `subjects_avoided` da 012: a saída do
-- modelo é VALIDADA pelo código (documento e assunto têm que estar no lote
-- mostrado), e o quanto foi descartado só é auditável se estiver à vista.

ALTER TABLE lucien_runs ADD COLUMN IF NOT EXISTS docs_seen          INT NOT NULL DEFAULT 0;
ALTER TABLE lucien_runs ADD COLUMN IF NOT EXISTS doc_links_created  INT NOT NULL DEFAULT 0;
ALTER TABLE lucien_runs ADD COLUMN IF NOT EXISTS doc_links_rejected INT NOT NULL DEFAULT 0;

ALTER TABLE lucien_runs
  DROP CONSTRAINT IF EXISTS lucien_runs_mode_check;
ALTER TABLE lucien_runs
  ADD CONSTRAINT lucien_runs_mode_check
  CHECK (mode IN ('incremental', 'reconstruction', 'assuntos', 'marcacao', 'documentos'));
